def _boundary_pattern(phrase: str) -> re.Pattern[str]:
    return re.compile(rf"(?<!\w){re.escape(phrase)}(?!\w)", re.IGNORECASE)


def _phrase_entries() -> list[tuple[str, str, str]]:
    entries: list[tuple[str, str, str]] = []
    for language, phrases in PHRASES_BY_LANGUAGE.items():
        for source, target in phrases.items():
            entries.append((source.lower(), target, language))
    return sorted(entries, key=lambda item: len(item[0]), reverse=True)


PHRASE_ENTRIES = _phrase_entries()


def normalize_fact_text(text: str) -> TranslationResult:
    """Translate short everyday fact claims into the English rule language.

    This intentionally uses a conservative phrase glossary instead of a
    generative model: if a phrase is not recognized, we leave it alone.
    """
    original = canonicalize_text(text)
    if not original:
        return TranslationResult(original_text="", translated_text="", detected_language="unknown")

    working = original.lower().replace("ё", "е")
    working = re.sub(r"\s+[—–]\s+", " are ", working)
    working = re.sub(r"[.!?]+$", "", working).strip()

    replacements: list[str] = []
    language_hits: dict[str, int] = {}
    for source, target, language in PHRASE_ENTRIES:
        pattern = _boundary_pattern(source)
        if not pattern.search(working):
            continue
        working = pattern.sub(f" {target} ", working)
        replacements.append(f"{language}:{source}->{target}")
        language_hits[language] = language_hits.get(language, 0) + 1

    if not replacements:
        return TranslationResult(original_text=original, translated_text=original, detected_language="en")

    working = re.sub(r"\b[ld]'\s*", " ", working, flags=re.IGNORECASE)
    article_pattern = r"\b(?:" + "|".join(re.escape(item) for item in sorted(ARTICLES, key=len, reverse=True)) + r")\b"
    working = re.sub(article_pattern, " ", working, flags=re.IGNORECASE)
    translated = canonicalize_text(working)
    translated = re.sub(r"\s+", " ", translated).strip(" .")
    translated = _insert_missing_copula(translated)
    detected_language = max(language_hits, key=language_hits.get) if language_hits else "unknown"
    return TranslationResult(
        original_text=original,
        translated_text=translated,
        detected_language=detected_language,
        replacements=tuple(replacements),
    )


def _insert_missing_copula(text: str) -> str:
    """Repair short translated claims from languages that often omit "is"."""
    tokens = (text or "").split()
    if len(tokens) < 2:
        return text
    verbs = {
        "is",
        "are",
        "was",
        "were",
        "can",
        "cannot",
        "live",
        "lives",
        "orbit",
        "orbits",
        "cause",
        "causes",
        "cure",
        "cures",
        "include",
        "includes",
    }
    if any(token in verbs for token in tokens):
        return text
    return f"{tokens[0]} is {' '.join(tokens[1:])}"
